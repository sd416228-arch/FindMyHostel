def cast_debug(value):
    value = str(value).strip().lower()
    if value in {'true', '1', 'yes', 'y', 'on', 'debug', 'development', 'dev'}:
        return True
    if value in {'false', '0', 'no', 'n', 'off', 'release', 'production', 'prod'}:
        return False
    raise ValueError(f'Invalid DEBUG value: {value}')


